import { TMDB_API_BASE_URL } from '@/lib/constants'
import type { paths } from '@/types/schema/tmdb-api-schema' // generated by openapi-typescript
import type {
  HTTPMethodPaths,
  OmitResponses,
  TmdbHTTPMethods,
} from '@/types/utils'

// todo: unsure if the P default type is correct (quite confident it is). I don't want to have to pass a value to it. It's defaulting to the union of all valid paths
// todo: along the same line, unsure if the default on A is correct (quite confident it is). Because P is all valid paths, I think this default will be the union of the types shared for all possible paths.
// todo: remove never types from args. Because almost every key is optional the never types are converted to undefined which obscures the required arguments.
export function constructTmdbRequest<
  M extends TmdbHTTPMethods,
  P extends HTTPMethodPaths<M>,
  A extends OmitResponses<paths[P][Lowercase<M>]> = OmitResponses<
    paths[P][Lowercase<M>]
  >,
>(method: M, path: P, args?: A) {
  // todo: args & return type
  // todo: separate args.query and append it to the URL
  const q = args?.parameters.query
  // todo: if args.header add it to header
  const h = args?.parameters.header?.['Content-Type']
  // todo if args.path replace the relevant route section i.e /account_id/
  const p = args?.parameters.path
  // todo if args.requestBody.content.RAW_BODY add to body
  const b = args?.requestBody?.content['application/json'].RAW_BODY

  const req = fetch(`${TMDB_API_BASE_URL}${path}`, {
    method,
  })

  return req
}
